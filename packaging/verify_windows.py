"""Exercise the actual frozen binaries without credentials or proxy changes."""
import json
import os
from pathlib import Path
import subprocess
import tempfile

root = Path('dist/CidarenAssistant-Windows-x64').resolve()
report = Path('build/windows-app-selftest.json').resolve()
report.parent.mkdir(exist_ok=True, parents=True)
process = subprocess.run([str(root / 'CidarenAssistant.exe'), '--build-selftest', str(report)],
                         cwd=tempfile.gettempdir(), timeout=120)
assert process.returncode == 0, report.read_text() if report.exists() else process.returncode
result = json.loads(report.read_text())
assert result['window_created'] and result['model_loaded'] and result['frozen'], result
helper = subprocess.run([str(root / 'mitmdump.exe'), '--version'], cwd=tempfile.gettempdir(),
                        capture_output=True, text=True, timeout=90)
print(helper.stdout)
assert helper.returncode == 0, helper.stderr
assert 'Mitmproxy' in helper.stdout, helper.stdout
# The second process exercises the same frozen entry used by the multi-window action.
second = report.with_name('windows-app-second-window.json')
native_env = os.environ.copy()
native_env.pop('QT_QPA_PLATFORM', None)
subprocess.run([str(root / 'CidarenAssistant.exe'), 'main.py', '--build-selftest', str(second)],
               cwd=tempfile.gettempdir(), env=native_env, check=True, timeout=120)
assert json.loads(second.read_text())['window_created']
for p in root.rglob('*'):
    assert p.name.lower() not in ('token.txt', 'wrong_memory.json', 'word_cache.sqlite3'), p
# Remove only logs generated by these offline self-tests before making the portable archive.
for p in (root / 'log/logs').glob('*.log'):
    p.unlink()
print('Frozen GUI, local model, independent launch and bundled capture helper passed.')

(root / '使用说明.txt').write_text('解压整个文件夹后，双击 CidarenAssistant.exe 启动。无需安装 Python。请保持依赖文件和文件夹完整；mitmdump.exe 是内置获取 Token 使用的组件，不必单独运行。\n本构建为 Windows x64 便携测试版，未进行代码签名。\n',encoding='utf-8')
